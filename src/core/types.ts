// ─────────────────────────────────────────────────
// CodiReactor Core Types
// Shared type definitions used across all subsystems
// ─────────────────────────────────────────────────

/** A single subtitle cue with timing and text */
export interface SubtitleCue {
  id: string;
  startMs: number;
  endMs: number;
  text: string;
  translatedText?: string;
}

/** CEFR proficiency level */
export type CEFRLevel = 'A1' | 'A2' | 'B1' | 'B2' | 'C1' | 'C2' | 'UNK';

/** Word status in user vocabulary */
export type TokenStatus = 'known' | 'suggested' | 'learning' | 'ignored' | 'special';

/** An enriched token ready for overlay rendering */
export interface EnrichedToken {
  /** Original text including whitespace/punctuation */
  text: string;
  /** Lowercase, stripped of punctuation */
  cleanText: string;
  /** Root dictionary form */
  lemma: string;
  /** Part of speech */
  pos: string;
  /** Frequency rank 1–20000+ (1 = most common) */
  frequencyRank: number;
  /** CEFR level */
  cefrLevel: CEFRLevel;
  /** User vocabulary status */
  status: TokenStatus;
  /** CSS hex color for rendering */
  color: string;
  /** Whether to render with border outline */
  outline: boolean;
  /** True for punctuation-only tokens (commas, periods, etc.) */
  isPunctuation: boolean;
  /** True if this is a whitespace segment */
  isWhitespace: boolean;
}

/** Color palette for token statuses */
export const TOKEN_COLORS: Record<TokenStatus, string> = {
  known: '#4ade80',      // Mint green
  suggested: '#fb923c',  // Warm orange
  learning: '#a855f7',   // Deep purple
  ignored: '#8c8c8c',    // Muted gray
  special: '#2dd4bf',    // Cyan/teal
} as const;

/** A parsed caption track containing all cues for a language */
export interface CaptionTrack {
  language: string;
  languageName: string;
  isAutoGenerated: boolean;
  cues: SubtitleCue[];
}

/** Language option available on a platform */
export interface LanguageOption {
  code: string;
  name: string;
  isAutoGenerated: boolean;
}

/** Frequency database entry */
export interface FrequencyEntry {
  rank: number;
  cefr: CEFRLevel;
  pos: string;
}

/** Offline dictionary entry */
export interface DictionaryEntry {
  word: string;
  ipa: string;
  audioUrl?: string;
  senses: Array<{
    pos: string;
    glosses: string[];
    examples?: string[];
  }>;
}

/** Online dictionary API result */
export interface DictionaryResult {
  word: string;
  phonetic?: string;
  audioUrl?: string;
  meanings: Array<{
    partOfSpeech: string;
    definitions: Array<{
      definition: string;
      example?: string;
    }>;
  }>;
  sourceUrls?: string[];
}

/** Saved vocabulary item */
export interface SavedItem {
  id: string;
  word: string;
  cleanWord: string;
  lemma: string;
  translation: string;
  phonetic: string;
  pos: string;
  sentenceTarget: string;
  sentenceNative: string;
  sourcePlatform: 'youtube' | 'netflix' | 'udemy' | 'coursera' | 'web' | 'local' | 'custom';
  sourceUrl: string;
  sourceTitle: string;
  timestampMs: number;
  dateAdded: number;
  colorTag: string;
  status: TokenStatus;
  // SRS metadata (SM-2)
  srsInterval: number;
  srsRepetitions: number;
  srsEaseFactor: number;
  srsDueDate: number;
}

/** User settings */
export interface UserSettings {
  targetLanguage: string;
  nativeLanguage: string;
  userLevel: number;              // frequency rank threshold (100, 500, 1000, 2000, 5000, 10000)
  suggestedToKnownRatio: number;  // 0.5 – 2.0 (default 1.0)
  machineTranslation: boolean;
  autoPause: boolean;
  showSubtitleOverlay: boolean;
  showTranscriptPanel: boolean;
  showMiniDictionary: boolean;
  hideSubtitlesMode: 'disabled' | 'hideNative' | 'hideTarget' | 'hideBoth';
  subtitleFontSize: 'small' | 'medium' | 'large' | 'xlarge';
  subtitleFontFamily: string;
  subtitleBgOpacity: number;      // 0–100
  rightClickAction: 'toggleStatus' | 'openDictionary';
  speakOnClick: 'yes' | 'no' | 'onHover';
  showColors: Record<TokenStatus, boolean>;
  customDictionaryUrls: string[];
  lexaPromptExplain: string;
  lexaPromptExamples: string;
  lexaPromptGrammar: string;
  srsCardsPerDay: number;
}

