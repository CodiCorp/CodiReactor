// ─────────────────────────────────────────────────
// WebReader Platform Adapter: Text Immersion Mode
// Converts web pages / articles into interactive
// sentence-by-sentence subtitle cues with TTS
// ─────────────────────────────────────────────────

import {
  BasePlatformAdapter,
  AdapterCapabilities,
  ControlElements,
} from './BasePlatformAdapter';
import { SubtitleCue, CaptionTrack, LanguageOption } from '../core/types';

export class WebReaderAdapter extends BasePlatformAdapter {
  readonly platformId = 'webreader' as const;

  private virtualTimeMs = 0;
  private durationMs = 0;
  private cachedCues: SubtitleCue[] = [];
  private mountPoint: HTMLElement | null = null;
  private isSpeaking = false;

  detect(): boolean {
    if (typeof window === 'undefined' || typeof document === 'undefined') return false;
    return (
      document.body?.hasAttribute('data-codireactor-reader') ||
      window.location.search.includes('codireactor_reader=1') ||
      !!document.querySelector('#codireactor-web-reader')
    );
  }

  getVideoElement(): HTMLVideoElement | null {
    // In web reader mode, there is no video element
    return null;
  }

  getScrubberContainer(): HTMLElement | null {
    return document.querySelector('#codireactor-reader-scrubber') || null;
  }

  getControlBarContainer(): HTMLElement | null {
    return document.querySelector('#codireactor-reader-controls') || null;
  }

  getOverlayMountPoint(): HTMLElement {
    if (this.mountPoint) return this.mountPoint;

    let el = document.getElementById('codireactor-reader-overlay');
    if (!el) {
      el = document.createElement('div');
      el.id = 'codireactor-reader-overlay';
      el.style.cssText = 'position: fixed; bottom: 20px; left: 50%; transform: translateX(-50%); z-index: 999999;';
      document.body?.appendChild(el);
    }
    this.mountPoint = el;
    return el;
  }

  /**
   * Extract text content from the article or page and slice into sentence cues.
   */
  async extractCaptions(language: string = 'en'): Promise<CaptionTrack[]> {
    const root =
      document.querySelector('article') ||
      document.querySelector('main') ||
      document.querySelector('.article-body') ||
      document.querySelector('#content') ||
      document.body;

    if (!root) return [];

    // Extract text blocks
    const paragraphs = Array.from(root.querySelectorAll('p, h1, h2, h3, blockquote'))
      .map(el => el.textContent?.trim() || '')
      .filter(text => text.length > 5);

    const cues: SubtitleCue[] = [];
    let currentMs = 0;
    const avgWordsPerMinute = 150;
    const msPerWord = (60 * 1000) / avgWordsPerMinute;

    for (let pIdx = 0; pIdx < paragraphs.length; pIdx++) {
      const text = paragraphs[pIdx];
      // Split paragraph into sentences
      const sentences = text.match(/[^.!?]+[.!?]+|\S+$/g) || [text];

      for (let sIdx = 0; sIdx < sentences.length; sIdx++) {
        const sentence = sentences[sIdx].trim();
        if (!sentence) continue;

        const words = sentence.split(/\s+/).length;
        const duration = Math.max(2000, words * msPerWord);
        const startMs = currentMs;
        const endMs = currentMs + duration;

        cues.push({
          id: `reader_cue_${pIdx}_${sIdx}`,
          startMs,
          endMs,
          text: sentence,
          plainText: sentence,
          formattedText: sentence,
        });

        currentMs = endMs + 500; // Small pause between sentences
      }
    }

    this.cachedCues = cues;
    this.durationMs = currentMs;

    return [
      {
        language,
        label: `Article Immersion (${language})`,
        isAutoGenerated: false,
        cues,
      },
    ];
  }

  async getAvailableLanguages(): Promise<LanguageOption[]> {
    return [
      { code: 'en', name: 'English (Extracted)', isAutoGenerated: false },
    ];
  }

  getCapabilities(): AdapterCapabilities {
    return {
      canInterceptSubtitles: true,
      canSeek: true,
      hasDRM: false,
      supportsMultipleTracks: false,
      canInjectControls: true,
    };
  }

  override seekTo(timeMs: number): void {
    const maxDuration = this.durationMs > 0 ? this.durationMs : Infinity;
    this.virtualTimeMs = Math.max(0, Math.min(timeMs, maxDuration));
    this.emitTimeUpdate(this.virtualTimeMs);

    // If SpeechSynthesis is available, read the sentence at this time
    const activeCue = this.cachedCues.find(
      c => c.startMs <= this.virtualTimeMs && c.endMs >= this.virtualTimeMs
    );

    if (activeCue && typeof window !== 'undefined' && 'speechSynthesis' in window) {
      try {
        window.speechSynthesis.cancel();
        const utterance = new SpeechSynthesisUtterance(activeCue.plainText);
        utterance.lang = 'en-US';
        this.isSpeaking = true;
        utterance.onend = () => {
          this.isSpeaking = false;
        };
        window.speechSynthesis.speak(utterance);
      } catch {
        // Ignore synthesis errors in headless or non-supported environments
      }
    }
  }

  override getCurrentTime(): number {
    return this.virtualTimeMs / 1000;
  }

  private emitTimeUpdate(timeMs: number): void {
    for (const cb of this.timeCallbacks) {
      try {
        cb(timeMs);
      } catch (e) {
        console.error('[WebReaderAdapter] timeUpdate error:', e);
      }
    }
  }

  override injectControls(uiElements: ControlElements): void {
    const container = this.getControlBarContainer();
    if (container && uiElements.toggleButton) {
      container.appendChild(uiElements.toggleButton);
    }
  }

  override injectTimelineMarkers(_cues: SubtitleCue[]): { remove: () => void } {
    return { remove: () => {} };
  }

  override destroy(): void {
    super.destroy();
    if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
      try {
        window.speechSynthesis.cancel();
      } catch {}
    }
    if (this.mountPoint && this.mountPoint.parentElement) {
      this.mountPoint.parentElement.removeChild(this.mountPoint);
      this.mountPoint = null;
    }
  }
}
