// ─────────────────────────────────────────────────
// Netflix Platform Adapter
// DOM-first MutationObserver strategy — resilient
// to internal Cadmium API rotations
// ─────────────────────────────────────────────────

import { BasePlatformAdapter, AdapterCapabilities } from './BasePlatformAdapter';
import { SubtitleCue, CaptionTrack, LanguageOption } from '../core/types';
import { parseTTML, autoParseSubtitles } from '../core/parser/subtitleParser';

// Netflix DOM selectors
const SELECTORS = {
  video: '.watch-video video, .NFPlayer video, video',
  playerContainer: '.watch-video--player-view, .NFPlayer',
  subtitleContainer: '.player-timedtext-text-container, .player-timedtext',
  subtitleSpan: '.player-timedtext-text-container span',
  controlBar: '.watch-video--bottom-controls-container, .PlayerControlsNeo__bottom-controls',
  progressBar: '.watch-video--scrubber-container, .scrubber-container',
} as const;

export class NetflixAdapter extends BasePlatformAdapter {
  readonly platformId = 'netflix' as const;

  private subtitleObserver: MutationObserver | null = null;
  private lastSubtitleText = '';
  private cueBuffer: SubtitleCue[] = [];
  private cueIndex = 0;

  detect(): boolean {
    return window.location.hostname.includes('netflix.com');
  }

  async initialize(): Promise<void> {
    await super.initialize();

    // Wait for video element to appear
    await this.waitForElement(SELECTORS.video, 15000);

    // Set up DOM-first subtitle observation
    this.setupSubtitleObserver();
    // Set up fetch interception as secondary source
    this.setupFetchInterception();
  }

  getVideoElement(): HTMLVideoElement | null {
    return document.querySelector<HTMLVideoElement>(SELECTORS.video);
  }

  getScrubberContainer(): HTMLElement | null {
    return document.querySelector<HTMLElement>(SELECTORS.progressBar);
  }

  getControlBarContainer(): HTMLElement | null {
    return document.querySelector<HTMLElement>(SELECTORS.controlBar);
  }

  getOverlayMountPoint(): HTMLElement {
    const player = document.querySelector<HTMLElement>(SELECTORS.playerContainer);
    if (player) return player;

    const video = this.getVideoElement();
    if (video?.parentElement) return video.parentElement;

    return document.body;
  }

  getCapabilities(): AdapterCapabilities {
    return {
      canInterceptSubtitles: true,
      canSeek: true,
      hasDRM: true, // Widevine DRM on audio/video, but subtitles are cleartext
      supportsMultipleTracks: true,
      canInjectControls: true,
    };
  }

  async extractCaptions(language?: string): Promise<CaptionTrack[]> {
    // Netflix doesn't expose captions in textTracks.
    // We rely on DOM observation + fetch interception for extraction.
    // Return buffered cues collected from observation.
    if (this.cueBuffer.length === 0) return [];

    return [{
      language: language || 'und',
      languageName: 'Netflix Captions',
      isAutoGenerated: false,
      cues: [...this.cueBuffer],
    }];
  }

  async getAvailableLanguages(): Promise<LanguageOption[]> {
    // Netflix subtitle languages are managed in its own settings UI.
    // We report what we can observe.
    return [{
      code: 'und',
      name: 'Active Subtitle Track',
      isAutoGenerated: false,
    }];
  }

  destroy(): void {
    if (this.subtitleObserver) {
      this.subtitleObserver.disconnect();
      this.subtitleObserver = null;
    }
    this.cueBuffer = [];
    super.destroy();
  }

  // ─── Primary: DOM MutationObserver (Stable) ──────

  /**
   * Observe Netflix's rendered subtitle container.
   * This is the MOST STABLE strategy — Netflix renders subtitles as
   * DOM text nodes regardless of internal player version changes.
   *
   * NEVER use window.netflix.appContext or Cadmium internal APIs.
   */
  private setupSubtitleObserver(): void {
    // Find or wait for the subtitle container
    const startObserving = (container: Element) => {
      this.subtitleObserver = new MutationObserver(() => {
        this.extractSubtitleFromDOM();
      });

      this.subtitleObserver.observe(container, {
        childList: true,
        subtree: true,
        characterData: true,
      });
    };

    // Try to find existing container
    const existing = document.querySelector(SELECTORS.subtitleContainer);
    if (existing) {
      startObserving(existing);
      return;
    }

    // Wait for it to appear (Netflix loads the player dynamically)
    const bodyObserver = new MutationObserver(() => {
      const container = document.querySelector(SELECTORS.subtitleContainer);
      if (container) {
        bodyObserver.disconnect();
        startObserving(container);
      }
    });

    bodyObserver.observe(document.body, { childList: true, subtree: true });
    this.cleanupFns.push(() => bodyObserver.disconnect());

    // Timeout fallback
    setTimeout(() => bodyObserver.disconnect(), 30000);
  }

  /**
   * Extract current subtitle text from Netflix's rendered DOM.
   */
  private extractSubtitleFromDOM(): void {
    const spans = document.querySelectorAll(SELECTORS.subtitleSpan);
    if (spans.length === 0) {
      // Subtitles cleared (no text visible)
      if (this.lastSubtitleText !== '') {
        this.lastSubtitleText = '';
      }
      return;
    }

    const text = Array.from(spans)
      .map(span => span.textContent || '')
      .join(' ')
      .trim();

    // Only emit if text actually changed
    if (text === this.lastSubtitleText || text.length === 0) return;
    this.lastSubtitleText = text;

    const video = this.getVideoElement();
    const currentMs = video ? video.currentTime * 1000 : 0;

    const cue: SubtitleCue = {
      id: `nf-dom-${this.cueIndex++}`,
      startMs: currentMs,
      endMs: currentMs + 5000, // Netflix doesn't expose end time in DOM
      text,
    };

    this.cueBuffer.push(cue);
    this.emitCaptions([cue]);
  }

  // ─── Secondary: Fetch Interception ───────────────

  /**
   * Intercept Netflix timed-text manifest fetches as a secondary data source.
   * This captures the full subtitle track with proper timing when available.
   */
  private setupFetchInterception(): void {
    const nonce = crypto.randomUUID();

    const onMessage = (event: MessageEvent) => {
      if (event.source !== window) return;
      if (event.data?.nonce !== nonce) return;
      if (event.data?.type !== 'CR_NETFLIX_SUBTITLE') return;

      try {
        const { body } = event.data.payload;
        const cues = autoParseSubtitles(body);

        if (cues.length > 0) {
          this.cueBuffer = cues;
          this.emitCaptions(cues);
        }
      } catch (err) {
        console.error('[NetflixAdapter] Error parsing intercepted subtitles:', err);
      }
    };

    window.addEventListener('message', onMessage);
    this.cleanupFns.push(() => window.removeEventListener('message', onMessage));

    // Inject MAIN world interceptor
    const script = document.createElement('script');
    script.textContent = `
      (function() {
        const NONCE = '${nonce}';
        const originalFetch = window.fetch;
        
        window.fetch = function(...args) {
          const url = typeof args[0] === 'string' ? args[0] : args[0]?.url || '';
          
          if (url.includes('timedtext') || url.includes('webvtt') || url.includes('dfxp')) {
            return originalFetch.apply(this, args).then(response => {
              const cloned = response.clone();
              cloned.text().then(body => {
                window.postMessage({
                  nonce: NONCE,
                  type: 'CR_NETFLIX_SUBTITLE',
                  payload: { url, body }
                }, '*');
              }).catch(() => {});
              return response;
            });
          }
          
          return originalFetch.apply(this, args);
        };
      })();
    `;
    (document.head || document.documentElement).appendChild(script);
    script.remove();
  }

  // ─── Utility ─────────────────────────────────────

  private waitForElement(selector: string, timeoutMs: number): Promise<HTMLElement | null> {
    return new Promise((resolve) => {
      const existing = document.querySelector<HTMLElement>(selector);
      if (existing) { resolve(existing); return; }

      const observer = new MutationObserver(() => {
        const el = document.querySelector<HTMLElement>(selector);
        if (el) { observer.disconnect(); resolve(el); }
      });

      observer.observe(document.body, { childList: true, subtree: true });
      setTimeout(() => { observer.disconnect(); resolve(null); }, timeoutMs);
    });
  }
}
