// ─────────────────────────────────────────────────
// Udemy Platform Adapter
// Extracts subtitles from Udemy's Video.js player
// ─────────────────────────────────────────────────

import { BasePlatformAdapter, AdapterCapabilities } from './BasePlatformAdapter';
import { SubtitleCue, CaptionTrack, LanguageOption } from '../core/types';
import { autoParseSubtitles } from '../core/parser/subtitleParser';

const SELECTORS = {
  video: 'video.vjs-tech, video[data-purpose="video-player"]',
  playerContainer: '.vjs-tech-container, [data-purpose="curriculum-item-viewer"]',
  controlBar: '.vjs-control-bar',
  progressBar: '.vjs-progress-holder',
} as const;

export class UdemyAdapter extends BasePlatformAdapter {
  readonly platformId = 'udemy' as const;

  private captionObserver: MutationObserver | null = null;
  private lastText = '';

  detect(): boolean {
    return window.location.hostname.includes('udemy.com');
  }

  async initialize(): Promise<void> {
    await super.initialize();
    this.setupTextTrackMonitoring();
    this.setupDOMCaptionObserver();
  }

  getVideoElement(): HTMLVideoElement | null {
    return document.querySelector<HTMLVideoElement>(SELECTORS.video);
  }

  getScrubberContainer(): HTMLElement | null {
    return document.querySelector<HTMLElement>(SELECTORS.progressBar);
  }

  getControlBarContainer(): HTMLElement | null {
    return document.querySelector<HTMLElement>(SELECTORS.controlBar);
  }

  getOverlayMountPoint(): HTMLElement {
    const container = document.querySelector<HTMLElement>(SELECTORS.playerContainer);
    if (container) return container;
    const video = this.getVideoElement();
    if (video?.parentElement) return video.parentElement;
    return document.body;
  }

  getCapabilities(): AdapterCapabilities {
    return {
      canInterceptSubtitles: true,
      canSeek: true,
      hasDRM: false,
      supportsMultipleTracks: true,
      canInjectControls: true,
    };
  }

  async extractCaptions(language?: string): Promise<CaptionTrack[]> {
    const video = this.getVideoElement();
    if (!video) return [];

    const tracks: CaptionTrack[] = [];
    const textTracks = Array.from(video.textTracks || []);

    for (const track of textTracks) {
      if (language && track.language !== language) continue;
      if (!track.cues) continue;

      const cues: SubtitleCue[] = [];
      for (let i = 0; i < track.cues.length; i++) {
        const cue = track.cues[i] as VTTCue;
        cues.push({
          id: `udemy-${i}`,
          startMs: cue.startTime * 1000,
          endMs: cue.endTime * 1000,
          text: cue.text.replace(/<[^>]+>/g, ''),
        });
      }

      tracks.push({
        language: track.language || 'und',
        languageName: track.label || track.language || 'Unknown',
        isAutoGenerated: false,
        cues,
      });
    }

    return tracks;
  }

  async getAvailableLanguages(): Promise<LanguageOption[]> {
    const video = this.getVideoElement();
    if (!video) return [];

    return Array.from(video.textTracks || []).map(track => ({
      code: track.language || 'und',
      name: track.label || track.language || 'Unknown',
      isAutoGenerated: false,
    }));
  }

  destroy(): void {
    if (this.captionObserver) {
      this.captionObserver.disconnect();
      this.captionObserver = null;
    }
    super.destroy();
  }

  private setupTextTrackMonitoring(): void {
    const video = this.getVideoElement();
    if (!video) return;

    const onCueChange = () => {
      const tracks = Array.from(video.textTracks || []);
      for (const track of tracks) {
        if (track.mode === 'showing' && track.activeCues) {
          const text = Array.from(track.activeCues)
            .map(c => (c as VTTCue).text)
            .join(' ')
            .replace(/<[^>]+>/g, '')
            .trim();

          if (text && text !== this.lastText) {
            this.lastText = text;
            const currentMs = video.currentTime * 1000;
            this.emitCaptions([{
              id: `udemy-live-${Date.now()}`,
              startMs: currentMs,
              endMs: currentMs + 5000,
              text,
            }]);
          }
        }
      }
    };

    // Listen for cuechange on all tracks
    for (const track of Array.from(video.textTracks || [])) {
      track.addEventListener('cuechange', onCueChange);
      this.cleanupFns.push(() => track.removeEventListener('cuechange', onCueChange));
    }
  }

  private setupDOMCaptionObserver(): void {
    // Udemy sometimes uses custom caption rendering
    const container = document.querySelector('.vjs-text-track-display');
    if (!container) return;

    this.captionObserver = new MutationObserver(() => {
      const text = container.textContent?.trim() || '';
      if (text && text !== this.lastText) {
        this.lastText = text;
        const video = this.getVideoElement();
        const currentMs = video ? video.currentTime * 1000 : 0;
        this.emitCaptions([{
          id: `udemy-dom-${Date.now()}`,
          startMs: currentMs,
          endMs: currentMs + 5000,
          text,
        }]);
      }
    });

    this.captionObserver.observe(container, { childList: true, subtree: true, characterData: true });
  }
}
