// ─────────────────────────────────────────────────
// Generic HTML5 Video Adapter
// Works on any page with a <video> element
// Supports native TextTrack + drag-drop subtitle files
// ─────────────────────────────────────────────────

import { BasePlatformAdapter, AdapterCapabilities } from './BasePlatformAdapter';
import { SubtitleCue, CaptionTrack, LanguageOption } from '../core/types';
import { autoParseSubtitles } from '../core/parser/subtitleParser';

export class GenericVideoAdapter extends BasePlatformAdapter {
  readonly platformId = 'generic' as const;

  private videoObserver: MutationObserver | null = null;
  private lastText = '';

  detect(): boolean {
    return !!document.querySelector('video');
  }

  async initialize(): Promise<void> {
    await super.initialize();
    this.setupTextTrackMonitoring();
    this.setupDragDropSubtitle();
  }

  getVideoElement(): HTMLVideoElement | null {
    // Find the largest/most visible video element on the page
    const videos = Array.from(document.querySelectorAll<HTMLVideoElement>('video'));
    if (videos.length === 0) return null;
    if (videos.length === 1) return videos[0];

    // Return the largest video by area
    return videos.reduce((best, v) => {
      const bestArea = best.videoWidth * best.videoHeight;
      const vArea = v.videoWidth * v.videoHeight;
      return vArea > bestArea ? v : best;
    });
  }

  getScrubberContainer(): HTMLElement | null {
    return null; // Generic — no standard scrubber container
  }

  getControlBarContainer(): HTMLElement | null {
    return null; // Generic — no standard control bar
  }

  getOverlayMountPoint(): HTMLElement {
    const video = this.getVideoElement();
    if (video?.parentElement) return video.parentElement;
    return document.body;
  }

  getCapabilities(): AdapterCapabilities {
    return {
      canInterceptSubtitles: false,
      canSeek: true,
      hasDRM: false,
      supportsMultipleTracks: true,
      canInjectControls: false,
    };
  }

  async extractCaptions(language?: string): Promise<CaptionTrack[]> {
    const video = this.getVideoElement();
    if (!video) return [];

    const tracks: CaptionTrack[] = [];
    const textTracks = Array.from(video.textTracks || []);

    for (const track of textTracks) {
      if (language && track.language !== language) continue;
      if (!track.cues) continue;

      const cues: SubtitleCue[] = [];
      for (let i = 0; i < track.cues.length; i++) {
        const cue = track.cues[i] as VTTCue;
        cues.push({
          id: `generic-${i}`,
          startMs: cue.startTime * 1000,
          endMs: cue.endTime * 1000,
          text: cue.text.replace(/<[^>]+>/g, ''),
        });
      }

      tracks.push({
        language: track.language || 'und',
        languageName: track.label || track.language || 'Unknown',
        isAutoGenerated: false,
        cues,
      });
    }

    return tracks;
  }

  async getAvailableLanguages(): Promise<LanguageOption[]> {
    const video = this.getVideoElement();
    if (!video) return [];

    return Array.from(video.textTracks || []).map(track => ({
      code: track.language || 'und',
      name: track.label || track.language || 'Unknown',
      isAutoGenerated: false,
    }));
  }

  destroy(): void {
    if (this.videoObserver) {
      this.videoObserver.disconnect();
      this.videoObserver = null;
    }
    super.destroy();
  }

  // ─── Private ─────────────────────────────────────

  private setupTextTrackMonitoring(): void {
    const video = this.getVideoElement();
    if (!video) return;

    const onCueChange = () => {
      const tracks = Array.from(video.textTracks || []);
      for (const track of tracks) {
        if (track.mode === 'showing' && track.activeCues) {
          const text = Array.from(track.activeCues)
            .map(c => (c as VTTCue).text)
            .join(' ')
            .replace(/<[^>]+>/g, '')
            .trim();

          if (text && text !== this.lastText) {
            this.lastText = text;
            const currentMs = video.currentTime * 1000;
            this.emitCaptions([{
              id: `generic-live-${Date.now()}`,
              startMs: currentMs,
              endMs: currentMs + 5000,
              text,
            }]);
          }
        }
      }
    };

    for (const track of Array.from(video.textTracks || [])) {
      track.addEventListener('cuechange', onCueChange);
      this.cleanupFns.push(() => track.removeEventListener('cuechange', onCueChange));
    }
  }

  /**
   * Allow users to drag & drop .srt / .vtt / .sub files onto the video
   * to load external subtitles.
   */
  private setupDragDropSubtitle(): void {
    const video = this.getVideoElement();
    if (!video?.parentElement) return;

    const container = video.parentElement;

    const onDragOver = (e: DragEvent) => {
      e.preventDefault();
      e.stopPropagation();
      container.style.outline = '2px dashed #2dd4bf';
    };

    const onDragLeave = () => {
      container.style.outline = '';
    };

    const onDrop = async (e: DragEvent) => {
      e.preventDefault();
      e.stopPropagation();
      container.style.outline = '';

      const files = e.dataTransfer?.files;
      if (!files || files.length === 0) return;

      for (const file of Array.from(files)) {
        const ext = file.name.split('.').pop()?.toLowerCase();
        if (!['srt', 'vtt', 'sub', 'ttml', 'dfxp', 'xml'].includes(ext || '')) continue;

        const content = await file.text();
        const cues = autoParseSubtitles(content);

        if (cues.length > 0) {
          this.emitCaptions(cues);
        }
      }
    };

    container.addEventListener('dragover', onDragOver);
    container.addEventListener('dragleave', onDragLeave);
    container.addEventListener('drop', onDrop);

    this.cleanupFns.push(() => {
      container.removeEventListener('dragover', onDragOver);
      container.removeEventListener('dragleave', onDragLeave);
      container.removeEventListener('drop', onDrop);
    });
  }
}
